"""
Test scenarios for a built plan: Anonymous Apex a person can run in the org,
written after the components exist so they use the real entry criteria,
field names and required fields instead of the planner's guesses.

Generated by one extra model call per plan (not per step). Running them is
flowtool/anon_apex.py, which wraps each script in a savepoint and rolls it back.
"""

from __future__ import annotations

import re
from typing import List, Literal, Optional

from pydantic import BaseModel, Field, field_validator

from .llm import DEFAULT_MAX_REPAIRS, IRGenerationResult, IRGenerator, Message, Provider
from .planner import Plan, StepResult

MAX_STEP_JSON = 6000

# The runner owns the transaction; a scenario that touches it would break the rollback.
_FORBIDDEN = re.compile(
    r"Database\s*\.\s*(setSavepoint|rollback)|System\s*\.\s*(schedule|enqueueJob)|"
    r"Database\s*\.\s*executeBatch|@future",
    re.IGNORECASE,
)


class TestScenario(BaseModel):
    __test__ = False  # not a pytest class, despite the name

    title: str = Field(description="Short name, e.g. 'Closed Won opportunity creates a renewal task'.")
    kind: Literal["positive", "negative", "bulk"] = Field(
        description="positive: the case the request describes. negative: a record that must "
        "NOT trigger it. bulk: 200 records in one transaction, to expose limit problems."
    )
    covers: Optional[str] = Field(
        default=None, description="Name of the plan step this exercises, if it is about one step."
    )
    apex: str = Field(
        description="Anonymous Apex body: statements only, no class or method declarations."
    )
    expect: str = Field(description="What a person should see when it passes, in one or two sentences.")

    @field_validator("apex")
    @classmethod
    def apex_is_runnable_as_is(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("apex is empty")
        hit = _FORBIDDEN.search(v)
        if hit:
            raise ValueError(
                f"apex uses {hit.group(0)!r}: the runner wraps the script in its own savepoint "
                "and rolls it back, and asynchronous work cannot run inside that transaction. "
                "Cover that case in `expect` as a manual step instead."
            )
        return v


class TestScenarios(BaseModel):
    __test__ = False

    scenarios: List[TestScenario] = Field(min_length=1, max_length=6)
    manual_notes: Optional[str] = Field(
        default=None,
        description="Anything that cannot be exercised by Anonymous Apex in a rolled-back "
        "transaction (async flow paths, scheduled jobs, UI-only screens) and how to check it by hand.",
    )


SCENARIO_SYSTEM_PROMPT = """\
You write test scenarios for Salesforce components that were just generated, as \
Anonymous Apex a person pastes into the Developer Console of a sandbox.

You are given the original request and each generated component as JSON. Read \
the real entry criteria, fields and logic from it - do not invent names.

## Rules for every script

- Statements only: no class, interface or method declarations. Local variables are fine.
- It runs inside a transaction that is rolled back afterwards, so it may insert and \
update freely. Do NOT call Database.setSavepoint or Database.rollback, System.schedule, \
System.enqueueJob, Database.executeBatch or use @future - asynchronous work cannot run in \
a rolled-back transaction. Describe any such case in `manual_notes` instead.
- Create all data the scenario needs inside the script. Never hard-code a record Id and \
never rely on existing org data. Fill every required field the components or the standard \
object need.
- Check the outcome with System.assertEquals / System.assert and a message that says what \
went wrong, so a failure reads clearly. Re-query records after the DML to see what a \
flow or trigger changed.
- Keep a bulk scenario to a single insert or update of 200 records in one list, never \
a loop of single DML calls.

## Which scenarios

Two to five, most valuable first:
1. `positive` - the exact case the request describes.
2. `negative` - a record that must NOT fire the automation (fails the entry criteria).
3. `bulk` - 200 records at once, whenever a Flow or Apex runs on record save or processes \
a collection. This is the scenario that exposes SOQL/DML-in-loop and CPU problems, so \
make it genuinely 200.
Add more only for a distinct risk the components visibly carry (a validation rule that \
blocks, a branch with a different outcome).

`expect` says what a person sees when it passes. `covers` names the plan step it tests.
"""


def _trim(text: str) -> str:
    return text if len(text) <= MAX_STEP_JSON else text[:MAX_STEP_JSON] + "\n...(truncated)"


def scenario_brief(plan: Plan, steps: List[StepResult], request: Optional[str] = None) -> str:
    parts: List[str] = []
    if request:
        parts.append(f"## Request\n{request}")
    if plan.reasoning:
        parts.append(f"## Plan\n{plan.reasoning}")
    if plan.how_to_test:
        parts.append(f"## The planner's own test notes\n{plan.how_to_test}")
    parts.append("## Components")
    for r in steps:
        parts.append(
            f"### {r.step.artifact_type}: {r.step.name}\n"
            + _trim(r.value.model_dump_json(exclude_none=True))
        )
    return "\n\n".join(parts)


class ScenarioGenerator(IRGenerator[TestScenarios]):
    def __init__(self, provider: Provider, max_repairs: int = DEFAULT_MAX_REPAIRS):
        super().__init__(provider, TestScenarios, SCENARIO_SYSTEM_PROMPT, max_repairs)

    def _describe(self, value: TestScenarios) -> str:
        return f"{len(value.scenarios)} scenario(s)"

    def generate(
        self, plan: Plan, steps: List[StepResult], request: Optional[str] = None,
    ) -> IRGenerationResult[TestScenarios]:
        return self._validated([Message(role="user", content=scenario_brief(plan, steps, request))])
